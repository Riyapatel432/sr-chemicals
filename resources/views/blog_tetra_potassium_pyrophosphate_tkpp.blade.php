                <h2 class="bl-h2">Key Industrial Applications of TKPP</h2>
                <p class="bl-p">Due to its high solubility and effective mineral-binding capabilities, TKPP is used across several major sectors:</p>

                <div class="bl-box mb-25">
                    <h3 class="bl-box-title" style="font-size: 18px; color: #1a2340;">1. Liquid Detergents &amp; Cleaning Formulations</h3>
                    <p class="bl-box-p" style="margin-bottom: 0;">TKPP serves as a high-performance builder and dispersing agent in liquid detergents and industrial cleaners. It helps soften water by sequestering calcium and magnesium ions, preventing dirt redeposition and improving overall washing efficiency.</p>
                </div>

                <div class="bl-box mb-25">
                    <h3 class="bl-box-title" style="font-size: 18px; color: #1a2340;">2. Surface Treatment &amp; Metal Finishing</h3>
                    <p class="bl-box-p" style="margin-bottom: 0;">In metal processing and surface treatment, TKPP acts as a chelating and cleaning agent, helping remove oxides, scale, and impurities before coating or plating operations.</p>
                </div>

                <div class="bl-box mb-25">
                    <h3 class="bl-box-title" style="font-size: 18px; color: #1a2340;">3. Paints, Coatings, and Pigment Dispersion</h3>
                    <p class="bl-box-p" style="margin-bottom: 0;">Thanks to its excellent dispersion properties, TKPP prevents clumping and maintains uniform viscosity in paint and coating formulations.</p>
                </div>

                <div class="bl-box mb-30">
                    <h3 class="bl-box-title" style="font-size: 18px; color: #1a2340;">4. Boiler Descaling &amp; Water Treatment</h3>
                    <p class="bl-box-p" style="margin-bottom: 0;">In industrial boiler systems, TKPP helps dissolve and prevent scale buildup (boiler descaling), extending equipment lifespan and optimizing heat transfer efficiency.</p>
