                <h2 class="bl-h2">1. Role of SHMP in Industrial Water Treatment</h2>
                <p class="bl-p">In industrial boilers, cooling towers, and municipal water systems, hard water minerals can precipitate out of solution, leading to severe scaling on heat exchanger surfaces and pipe walls.</p>

                <div class="bl-formula" style="font-size: 15px; font-weight: 600; background: #f8fbff; border: 1px solid #bed6f7; padding: 16px; margin: 20px 0;">
                    Ca²⁺ (Hardness Ion) + SHMP (Sequestering Agent) ➔ [Ca-SHMP Complex] (Soluble / Non-Scaling)
                </div>

                <div class="bl-box mb-25">
                    <h3 class="bl-box-title" style="font-size: 17px; color: #1a2340;">Key Functions in Water Conditioning:</h3>
                    <ul class="bl-ul mb-0" style="padding-left: 18px;">
                        <li><strong>Scale Inhibition:</strong> SHMP binds to dissolved calcium and magnesium ions, holding them in a clear, soluble complex even under high-temperature boiler conditions.</li>
                        <li><strong>Corrosion Control:</strong> By forming a thin, protective polyphosphate film along internal metallic piping, SHMP reduces oxide formation and extends equipment service life.</li>
                        <li><strong>Threshold Effect:</strong> SHMP exhibits threshold inhibition, meaning tiny quantities (1–2 ppm) can prevent large volumes of calcium carbonate (CaCO₃) from precipitating out.</li>
                    </ul>
                </div>

                <div style="background: #eef6ff; border-left: 4px solid #0d6efd; padding: 16px 20px; border-radius: 0 8px 8px 0; margin-bottom: 30px;">
