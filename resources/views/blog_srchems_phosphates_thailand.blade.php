                {{-- Section 2 --}}
                <h2 class="bl-h2">2. Trisodium Phosphate (TSP) &amp; Disodium Phosphate (DSP) in Automotive Pre-Treatment</h2>
                <p class="bl-p">Known as the "Detroit of Asia," Thailand hosts world-class automotive assembly and metal fabrication plants. Before steel or aluminum parts receive powder coatings, e-coatings, or protective paints, surfaces must undergo rigorous cleaning and conversion coating.</p>

                <h3 class="bl-box-title" style="font-size: 17px; margin-top: 20px; color: #1a2340;">Heavy-Duty Alkaline Degreasing with TSP</h3>
                <p class="bl-p"><a href="{{ route('trisodium_phosphate_anhydrous') }}" class="bl-link">Trisodium Phosphate</a> (Na₃PO₄) yields a high-alkalinity bath (pH &approx; 12) required to saponify heavy drawing oils, grease, and shop dirt. Utilizing SR Chems <a href="{{ route('trisodium_phosphate_anhydrous') }}" class="bl-link">TSP Anhydrous</a> or <a href="{{ route('tri_sodium_phosphate_crystals') }}" class="bl-link">TSP Crystalline</a> prevents insoluble sludge buildup inside immersion tanks and prepares virgin metal surfaces for treatment.</p>

                <h3 class="bl-box-title" style="font-size: 17px; margin-top: 20px; color: #1a2340;">Iron Phosphating with DSP</h3>
                <p class="bl-p">Following degreasing, <a href="{{ route('di_sodium_phosphate_anhydrous_sr') }}" class="bl-link">Disodium Phosphate (Na₂HPO₄)</a> acts as a buffered iron phosphating agent (pH &approx; 8.8–9.2). It reacts with iron substrates to deposit a microscopic, porous iron phosphate layer that acts as an anchor for superior paint adhesion, prevents under-film corrosion, and inhibits flash-rusting during staging.</p>

